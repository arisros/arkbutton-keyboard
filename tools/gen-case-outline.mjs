/** Generate a 2D OUTLINE of the case footprint from case_main.stl, for the tent stand to match.
 *  The stand's cover/base were built from plate_flat (the flat bottom plate), whose outline does
 *  NOT track the case's rounded, flared rim — so a uniform inset can't make them line up. Instead
 *  we project the real case silhouette (manifold project()), keep the largest contour (the outer
 *  boundary; the rest are tiny mesh-shadow slivers), simplify it, and emit it as an OpenSCAD module
 *  `case_outline()`. tent_stand.scad's foot2d() then uses THIS instead of plate_flat → the stand
 *  footprint is the case footprint, and a small offset() tucks the cover just under the rim.
 *    node tools/gen-case-outline.mjs
 */
import { initManifold, loadManifold } from './stl.mjs'
import { writeFileSync } from 'fs'

const SIMPLIFY = 0.3   // mm — collapse boundary detail below this (smooths the jagged mesh shadow)

await initManifold()
const m = await loadManifold(new URL('../cosmos/case_main.stl', import.meta.url).pathname)
const cs = m.project().simplify(SIMPLIFY)
const polys = cs.toPolygons()
// signed area of each contour; the outer boundary is the one with the largest magnitude
const area = p => { let a = 0; for (let i = 0; i < p.length; i++) { const [x1, y1] = p[i], [x2, y2] = p[(i + 1) % p.length]; a += x1 * y2 - x2 * y1 } return a / 2 }
let outer = polys[0], best = -1
for (const p of polys) { const a = Math.abs(area(p)); if (a > best) { best = a; outer = p } }
// ensure CCW (positive area) so OpenSCAD fills it solid
if (area(outer) < 0) outer = outer.slice().reverse()
const pts = outer.map(([x, y]) => `[${x.toFixed(2)},${y.toFixed(2)}]`).join(',')
const out = `// AUTO-GENERATED by tools/gen-case-outline.mjs — do not edit by hand.
// Outer silhouette of cosmos/case_main.stl (manifold project, simplify ${SIMPLIFY} mm). ${outer.length} pts, area ${best.toFixed(0)} mm^2.
module case_outline() polygon(points=[${pts}]);
`
writeFileSync(new URL('../cosmos/case_outline.scad', import.meta.url).pathname, out)
console.log(`wrote cosmos/case_outline.scad — ${outer.length} pts, outer area ${best.toFixed(0)} mm², bbox`,
  [Math.min(...outer.map(p => p[0])), Math.max(...outer.map(p => p[0])), Math.min(...outer.map(p => p[1])), Math.max(...outer.map(p => p[1]))].map(v => +v.toFixed(1)))
